/**
 * The `providers` namespace: copy owned by the provider configuration forms in
 * Settings → API Configuration.
 *
 * This is the surface with the most repeated copy in the app — every provider form
 * renders the same API-key field, base-URL toggle, model picker and model-info row —
 * so the shared strings live together at the top and provider-specific ones below
 * them, named after the file that owns them.
 *
 * Two conventions this table depends on, both enforced by tests:
 *   - Values are the *English* strings the fields already shipped. The English column
 *     is what the e2e suites and the component specs assert on, so changing one here
 *     is a behaviour change, not a wording tweak.
 *   - A sentence with a variable part is one key with a `{placeholder}`, and every
 *     locale must keep that marker (`i18n.test.ts`). This is also why the API-key
 *     signup sentence says "your {provider} API key" rather than `a`/`an`: English
 *     needs the article to agree with the next word, and no other language has a use
 *     for that seam — a translation that had to keep an `{article}` marker would be
 *     carrying English grammar it cannot place.
 */
